// Audit « ne fait pas IA » (docs/SPEC.md §7 bis.6) : liste les motifs interdits restants
// dans ce que voit le visiteur, avec le fichier et la ligne. Code de sortie 1 s'il en reste.
// Usage : npm run audit:ai
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, extname } from "node:path";

const roots = ["src", "public", "supabase/templates"];
const extensions = new Set([".ts", ".tsx", ".css", ".html", ".svg", ".json", ".webmanifest"]);
const ignored = new Set(["database.types.ts"]);

const rules = [
  { name: "Tiret long ou demi-cadratin", re: /[—–]/ },
  { name: "Formule creuse", re: /transformez votre|libérez votre potentiel|tout-en-un|boostez|révolutionnaire|game.?changer|next.?level/i },
  { name: "Texte de remplissage", re: /lorem ipsum|votre titre ici|your title here|placeholder text/i },
  { name: "Trace d'outil", re: /made with|built with|powered by|généré par (l')?ia|generated by/i },
  { name: "Emoji", re: /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u },
  { name: "Dégradé", re: /bg-gradient|linear-gradient|radial-gradient|from-(purple|violet|pink|fuchsia)/ },
  { name: "Arrondi hors charte (8 px uniquement)", re: /\brounded-(sm|md|lg|xl|2xl|3xl|full)\b/ },
  { name: "Icône cliché IA", re: /\b(Sparkles|Sparkle|Bot|BrainCircuit|Brain|Wand2|WandSparkles|Stars)\b/ },
  { name: "Preuve sociale non confirmée", re: /témoignage|testimonial|ils nous font confiance|(?<!\p{L})vu dans|\d+\s?% de temps/iu },
];

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* walk(path);
    else if (extensions.has(extname(name)) && !ignored.has(name)) yield path;
  }
}

const findings = [];
for (const root of roots) {
  for (const file of walk(root)) {
    readFileSync(file, "utf8").split("\n").forEach((line, i) => {
      for (const rule of rules) {
        if (rule.re.test(line)) findings.push(`${file}:${i + 1}  [${rule.name}]  ${line.trim().slice(0, 120)}`);
      }
    });
  }
}

if (findings.length) {
  console.log(`Audit « ne fait pas IA » : ${findings.length} point(s) à corriger\n`);
  console.log(findings.join("\n"));
  process.exit(1);
}
console.log("Audit « ne fait pas IA » : aucun motif interdit trouvé.");
